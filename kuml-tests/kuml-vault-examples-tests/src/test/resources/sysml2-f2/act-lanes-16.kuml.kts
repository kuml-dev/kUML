import dev.kuml.sysml2.dsl.sysml2Model

sysml2Model("Lanes16") {
    val person = activityPartition("Person")
    val vitec = activityPartition("Vitec")
    val fmcs = activityPartition("FMCS")

    val start = initialNode(partition = person)
    val a1 = actionDef(name = "Request opening", partition = person)
    val a2 = actionDef(name = "Check request", partition = vitec)
    val a3 = actionDef(name = "Plan route", partition = vitec)
    val a4 = actionDef(name = "Send command", partition = vitec)
    val a5 = actionDef(name = "Receive command", partition = fmcs)
    val a6 = actionDef(name = "Open door", partition = fmcs)
    val a7 = actionDef(name = "Report state", partition = fmcs)
    val a8 = actionDef(name = "Store state", partition = vitec)
    val a9 = actionDef(name = "Notify person", partition = vitec)
    val a10 = actionDef(name = "Show result", partition = person)
    val a11 = actionDef(name = "Confirm result", partition = person)
    val a12 = actionDef(name = "Archive", partition = vitec)
    val a13 = actionDef(name = "Audit", partition = vitec)
    val a14 = actionDef(name = "Close request", partition = person)
    val end = finalNode(partition = person)
    controlFlow(name = "f0", source = start, target = a1)
    controlFlow(name = "f1", source = a1, target = a2)
    controlFlow(name = "f2", source = a2, target = a3)
    controlFlow(name = "f3", source = a3, target = a4)
    controlFlow(name = "f4", source = a4, target = a5)
    controlFlow(name = "f5", source = a5, target = a6)
    controlFlow(name = "f6", source = a6, target = a7)
    controlFlow(name = "f7", source = a7, target = a8)
    controlFlow(name = "f8", source = a8, target = a9)
    controlFlow(name = "f9", source = a9, target = a10)
    controlFlow(name = "f10", source = a10, target = a11)
    controlFlow(name = "f11", source = a11, target = a12)
    controlFlow(name = "f12", source = a12, target = a13)
    controlFlow(name = "f13", source = a13, target = a14)
    controlFlow(name = "f14", source = a14, target = end)
    controlFlow(name = "retry", source = a10, target = a1)

    actDiagram("Lanes") {
        include(start)
        include(a1)
        include(a2)
        include(a3)
        include(a4)
        include(a5)
        include(a6)
        include(a7)
        include(a8)
        include(a9)
        include(a10)
        include(a11)
        include(a12)
        include(a13)
        include(a14)
        include(end)
    }
}
