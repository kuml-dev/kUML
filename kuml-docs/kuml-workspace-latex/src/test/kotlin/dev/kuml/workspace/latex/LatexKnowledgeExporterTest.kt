package dev.kuml.workspace.latex

import dev.kuml.workspace.latex.LatexTestSupport.main
import dev.kuml.workspace.latex.LatexTestSupport.text
import dev.kuml.workspace.pdf.ExportMetadata
import dev.kuml.workspace.pdf.ExportScope
import dev.kuml.workspace.pdf.PdfLanguage
import dev.kuml.workspace.pdf.source.WorkspaceSource
import io.kotest.assertions.throwables.shouldThrow
import io.kotest.core.spec.style.FunSpec
import io.kotest.matchers.shouldBe
import io.kotest.matchers.string.shouldContain
import io.kotest.matchers.string.shouldNotContain
import java.time.LocalDate

class LatexKnowledgeExporterTest :
    FunSpec({
        fun ws(extra: Map<String, String> = emptyMap()) =
            LatexTestSupport.workspace(
                files =
                    mapOf(
                        "index.md" to
                            LatexTestSupport.index(
                                links = listOf("kapitel/eins.md", "kapitel/zwei.md"),
                                extraFrontmatter = "subtitle: Untertitel\nauthor: Erika\nversion: 2.0\n",
                            ),
                        "kapitel/eins.md" to LatexTestSupport.doc(title = "Eins", body = "Text.\n\n```kuml\nx\n```\n"),
                        "kapitel/zwei.md" to LatexTestSupport.doc(title = "Zwei", body = "Text.\n\n```kuml {name=\"Zweites\"}\ny\n```\n"),
                        "glossary/index.md" to "---\ntype: Glossary\ntitle: Glossar\n---\n# Glossar\n\nBegriff.\n",
                        "lose/anhang.md" to LatexTestSupport.doc(title = "Anhang", body = "Lose."),
                    ) + extra,
            )

        test("documents come in the order of the PDF plan, one chapter each, glossary and appendix after") {
            val w = ws()
            val p = LatexTestSupport.prepare(ws = w)
            val plan = WorkspaceSource.plan(workspace = w, scope = ExportScope.All)
            p.documentCount shouldBe plan.all.size
            val main = p.main()
            val order =
                listOf(
                    "\\chapter{Eins}",
                    "\\chapter{Zwei}",
                    "\\chapter{Glossary}".replace("Glossary", "Glossar"),
                    "\\chapter{Weitere Dokumente}",
                    "\\section{Anhang}",
                )
            val positions = order.map { main.indexOf(it) }
            positions.all { it >= 0 } shouldBe true
            positions shouldBe positions.sorted()
        }

        test("the number of included figures matches the diagrams of the plan") {
            val w = ws()
            val p = LatexTestSupport.prepare(ws = w)
            val diagrams = WorkspaceSource.plan(workspace = w, scope = ExportScope.All).all.sumOf { it.kumlBlocks.size }
            p.figureCount + p.excludedFigureCount shouldBe diagrams
            p.files.count { it.path.startsWith("figures/") } shouldBe diagrams
        }

        test("header: report class, German babel from index.md, deterministic date, escaped title block") {
            val main = LatexTestSupport.prepare(ws = ws()).main()
            main shouldContain "\\documentclass[11pt,a4paper]{report}"
            main shouldContain "\\usepackage[shorthands=off,ngerman]{babel}"
            main shouldContain "\\date{2026-11-07}"
            main shouldContain "\\title{Handbuch\\\\[1ex]\\large Untertitel\\\\[1ex]\\normalsize 2.0}"
            main shouldContain "\\author{Erika}"
            main shouldContain "% Generated by kUML test"
            main shouldContain "\\tableofcontents"
        }

        test("package order: babel before the shared preamble, hyperref last") {
            val main = LatexTestSupport.prepare(ws = ws()).main()
            val babel = main.indexOf("{babel}")
            val preamble = main.indexOf("\\input{kuml-preamble}")
            val hyperref = main.indexOf("{hyperref}")
            (babel < preamble && preamble < hyperref) shouldBe true
        }

        test("options: english, no toc, metadata date") {
            val p =
                LatexTestSupport.prepare(
                    ws = ws(),
                    options =
                        LatexTestSupport.options {
                            copy(
                                language = PdfLanguage.EN,
                                toc = false,
                                metadata = ExportMetadata(date = LocalDate.of(2020, 1, 2), title = "T"),
                            )
                        },
                )
            val main = p.main()
            main shouldContain "{babel}".let { "english]{babel}" }
            main shouldContain "\\date{2020-01-02}"
            main shouldNotContain "\\tableofcontents"
            main shouldContain "\\chapter{Glossary}".let { "\\chapter{Glossary}" }
            main shouldContain "\\chapter{Further documents}"
        }

        test("the shared preamble and the main document are always written") {
            val p =
                LatexTestSupport.prepare(
                    ws =
                        ws(
                            extra =
                                mapOf(
                                    "kapitel/eins.md" to LatexTestSupport.doc(title = "Eins", body = "ohne Diagramm"),
                                    "kapitel/zwei.md" to LatexTestSupport.doc(title = "Zwei", body = "auch nicht"),
                                ),
                        ),
                )
            p.files.map { it.path }.takeLast(2) shouldBe listOf("kuml-preamble.tex", "main.tex")
            p.text("kuml-preamble.tex") shouldContain "\\usetikzlibrary"
        }

        test("a scope with no document is rejected, a folder scope narrows the export") {
            shouldThrow<LatexKnowledgeExportException> {
                LatexTestSupport.prepare(
                    ws = ws(),
                    options = LatexTestSupport.options { copy(scope = ExportScope.Folder("gibt-es-nicht")) },
                )
            }.code shouldBe LatexKnowledgeExportException.Code.EMPTY_SCOPE
            shouldThrow<LatexKnowledgeExportException> {
                LatexTestSupport.prepare(ws = ws(), options = LatexTestSupport.options { copy(scope = ExportScope.Folder("../x")) })
            }.code shouldBe LatexKnowledgeExportException.Code.PATH_OUTSIDE_ROOT
            val p = LatexTestSupport.prepare(ws = ws(), options = LatexTestSupport.options { copy(scope = ExportScope.Folder("kapitel")) })
            p.documentCount shouldBe 2
        }

        test("limits on documents and diagrams are enforced before any rendering") {
            var rendered = 0
            val counting =
                LatexDiagramSource { _, _, _ ->
                    rendered++
                    LatexDiagramOutcome.Failed("x")
                }
            shouldThrow<LatexKnowledgeExportException> {
                LatexTestSupport.prepare(
                    ws = ws(),
                    options = LatexTestSupport.options { copy(limits = limits.copy(maxDocuments = 2)) },
                    diagrams = counting,
                )
            }.code shouldBe LatexKnowledgeExportException.Code.LIMIT_DOCUMENTS
            shouldThrow<LatexKnowledgeExportException> {
                LatexTestSupport.prepare(
                    ws = ws(),
                    options = LatexTestSupport.options { copy(limits = limits.copy(maxDiagrams = 1)) },
                    diagrams = counting,
                )
            }.code shouldBe LatexKnowledgeExportException.Code.LIMIT_DIAGRAMS
            rendered shouldBe 0
        }

        test("characters pdflatex cannot typeset give one warning per document and no raw emoji in the output") {
            val p =
                LatexTestSupport.prepare(
                    ws =
                        ws(
                            extra =
                                mapOf(
                                    "kapitel/eins.md" to LatexTestSupport.doc(title = "Eins", body = "Hallo \uD83D\uDE00 und 日本"),
                                ),
                        ),
                )
            val warn = p.issues.filter { it.level == LatexIssueLevel.WARN }
            warn.size shouldBe 1
            warn.single().source shouldBe "kapitel/eins.md"
            p.main() shouldNotContain "\uD83D"
        }

        test("binary output files compare by content") {
            LatexOutputFile.Binary(path = "a", bytes = byteArrayOf(1)) shouldBe LatexOutputFile.Binary(path = "a", bytes = byteArrayOf(1))
        }
    })
