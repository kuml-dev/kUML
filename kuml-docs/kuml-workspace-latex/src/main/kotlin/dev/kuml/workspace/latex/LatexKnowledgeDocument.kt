package dev.kuml.workspace.latex

import dev.kuml.io.latex.LatexDocumentAssembler
import dev.kuml.workspace.pdf.source.SourceMetadata
import java.time.LocalDate

/** Builds `main.tex`. The package order is binding: babel before `kuml-preamble`, hyperref last. */
internal object LatexKnowledgeDocument {
    fun build(
        generator: String,
        labels: LatexLabels,
        metadata: SourceMetadata,
        date: LocalDate,
        toc: Boolean,
        body: String,
    ): String =
        buildString {
            appendLine("% Generated by ${LatexEscaper.commentSafe(generator)}")
            appendLine("\\documentclass[11pt,a4paper]{report}")
            appendLine("\\usepackage[utf8]{inputenc}")
            appendLine("\\usepackage[T1]{fontenc}")
            appendLine("\\usepackage{lmodern}")
            appendLine("\\usepackage{textcomp}")
            appendLine("\\usepackage{amssymb}")
            // shorthands=off: no active `"` in German, so diagram labels and quotes cannot be reinterpreted.
            appendLine("\\usepackage[shorthands=off,${labels.babel}]{babel}")
            appendLine("\\usepackage[margin=25mm]{geometry}")
            appendLine("\\usepackage{graphicx}")
            appendLine("\\usepackage{float}")
            appendLine("\\usepackage{longtable}")
            appendLine("\\usepackage{array}")
            appendLine("\\input{kuml-preamble}")
            appendLine("\\usepackage[hidelinks]{hyperref}")
            // A plain text marker, not a box: it also appears in chapter titles, table of contents and PDF bookmarks.
            appendLine("\\DeclareRobustCommand{\\kumlglyph}[1]{\\texttt{[#1]}}")
            appendLine(
                "\\DeclareRobustCommand{\\kumlmissing}[2]{\\par\\noindent\\fbox{\\parbox{0.94\\linewidth}{\\textbf{#1}\\\\[0.5ex]\\small #2}}\\par}",
            )
            appendLine("\\newenvironment{kumlcode}{\\begin{quote}\\parindent=0pt\\ttfamily\\small\\raggedright}{\\end{quote}}")
            appendLine("\\newcommand{\\kumlcodeinfo}[1]{\\par\\noindent{\\footnotesize\\textit{#1}}\\nopagebreak\\par}")
            append(LatexDocumentAssembler.figureMacro(placement = "htbp", maxHeight = "0.7"))
            appendLine("\\title{${title(metadata)}}")
            appendLine("\\author{${author(metadata)}}")
            appendLine("\\date{$date}")
            appendLine("\\begin{document}")
            appendLine("\\maketitle")
            if (toc) appendLine("\\tableofcontents")
            appendLine()
            append(body)
            appendLine("\\end{document}")
        }

    private fun title(m: SourceMetadata): String {
        val sb = StringBuilder(LatexEscaper.text(raw = m.title))
        m.subtitle?.takeIf { it.isNotBlank() }?.let { sb.append("\\\\[1ex]\\large ").append(LatexEscaper.text(raw = it)) }
        val extra = listOfNotNull(m.version, m.status).filter { it.isNotBlank() }
        if (extra.isNotEmpty()) {
            sb
                .append(
                    "\\\\[1ex]\\normalsize ",
                ).append(extra.joinToString(" \\textbullet{} ") { LatexEscaper.text(raw = it) })
        }
        return sb.toString()
    }

    private fun author(m: SourceMetadata): String =
        listOfNotNull(m.author, m.organization).filter { it.isNotBlank() }.joinToString(" \\and ") { LatexEscaper.text(raw = it) }
}
