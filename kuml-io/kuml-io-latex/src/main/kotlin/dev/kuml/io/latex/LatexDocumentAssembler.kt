package dev.kuml.io.latex

/** A figure of the main document: [input] is a relative path without `.tex`, always with `/` separators. */
public data class LatexFigure(
    val input: String,
    val caption: String?,
)

/** A figure that was written but is deliberately not included; it appears as a comment only. */
public data class LatexExcludedFigure(
    val input: String,
    val reason: String,
)

/** Builds the `main.tex` that collects the figures of a folder export. */
public object LatexDocumentAssembler {
    private val SAFE_INPUT = Regex("^[A-Za-z0-9][A-Za-z0-9._-]*(/[A-Za-z0-9][A-Za-z0-9._-]*)*$")

    /**
     * @param figures included figures, in the order given.
     * @param excluded figures that stay out of the document; only a comment line is written.
     * @param generator text of the header comment.
     */
    public fun mainDocument(
        figures: List<LatexFigure>,
        excluded: List<LatexExcludedFigure>,
        generator: String,
    ): String {
        figures.forEach { requireSafeInput(it.input) }
        excluded.forEach { requireSafeInput(it.input) }
        return buildString {
            appendLine("% Generated by ${commentSafe(generator)}")
            appendLine("\\documentclass{article}")
            appendLine("\\usepackage[margin=15mm]{geometry}")
            appendLine("\\usepackage{graphicx}")
            appendLine("\\usepackage{float}")
            appendLine("\\input{kuml-preamble}")
            appendLine("\\newsavebox{\\kumlbox}")
            appendLine("% \\kumlfigure{<file without .tex>}{<caption>}: scales a figure down to fit, never up.")
            appendLine("\\newcommand{\\kumlfigure}[2]{%")
            appendLine("  \\sbox{\\kumlbox}{\\input{#1}}%")
            appendLine("  \\begin{figure}[H]\\centering")
            appendLine("  \\ifdim\\wd\\kumlbox>\\linewidth")
            appendLine("    \\resizebox{\\linewidth}{!}{\\usebox{\\kumlbox}}%")
            appendLine("  \\else\\ifdim\\ht\\kumlbox>0.85\\textheight")
            appendLine("    \\resizebox{!}{0.85\\textheight}{\\usebox{\\kumlbox}}%")
            appendLine("  \\else")
            appendLine("    \\usebox{\\kumlbox}%")
            appendLine("  \\fi\\fi")
            appendLine("  \\caption{#2}")
            appendLine("  \\end{figure}%")
            appendLine("}")
            appendLine("\\begin{document}")
            for (f in figures) {
                val caption = f.caption?.let { escapeLatex(stripControl(it)) } ?: ""
                appendLine("\\kumlfigure{${f.input}}{$caption}")
            }
            for (e in excluded) appendLine("% excluded: ${e.input}.tex - ${commentSafe(e.reason)}")
            appendLine("\\end{document}")
        }
    }

    private fun requireSafeInput(input: String) {
        require(SAFE_INPUT.matches(input) && ".." !in input) { "Unsafe figure path: $input" }
    }
}
